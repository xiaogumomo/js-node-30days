DROP SCHEMA public CASCADE;
CREATE SCHEMA public ;

CREATE TABLE employees(
    emp_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY ,
    name TEXT NOT NULL ,
    hire_date DATE NOT NULL ,
    salary  NUMERIC(12,2) 
);

CREATE TABLE departments(
    dep_id BIGINT GENERATED  BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY ,
    dept_name TEXT NOT NULL UNIQUE,
    budget NUMERIC(12,2)
);

ALTER TABLE employees ADD COLUMN  dept_id BIGINT  NOT NULL  REFERENCES departments(dep_id) ON DELETE RESTRICT   ;
ALTER TABLE departments ADD COLUMN  manager_id BIGINT   UNIQUE REFERENCES employees(emp_id)  ON DELETE RESTRICT ;


CREATE TABLE projects(
    proj_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY ,
    pro_name TEXT NOT NULL ,
    content TEXT 
);

CREATE TABLE works_on(
    proj_id BIGINT REFERENCES projects(proj_id) ON DELETE CASCADE ,
    emp_id BIGINT REFERENCES employees(emp_id) ON DELETE CASCADE ,
    hours NUMERIC(5,2) NOT NULL,
    PRIMARY KEY (proj_id,emp_id)    
);


